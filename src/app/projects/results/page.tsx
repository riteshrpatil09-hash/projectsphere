"use client";

import Link from "next/link";
import { useEffect, useState } from "react";

export default function ResultsPage() {
  const [projects, setProjects] = useState<any[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    async function fetchProjects() {
      try {
        const storedPrefs = localStorage.getItem("projectSpherePrefs");
        const body = storedPrefs ? JSON.parse(storedPrefs) : {};
        
        const response = await fetch('/api/generate', {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
          },
          body: JSON.stringify(body),
        });

        if (response.ok) {
          const data = await response.json();
          if (Array.isArray(data)) {
            setProjects(data);
            localStorage.setItem('projectSphereResults', JSON.stringify(data));
          } else {
            setError("AI returned unexpected data format. Please try again.");
          }
        } else {
          setError("Failed to generate projects from AI. Please try again.");
        }
      } catch (error) {
        console.error("Error fetching projects", error);
        setError("Network error. Please check your connection.");
      } finally {
        setIsLoading(false);
      }
    }

    fetchProjects();
  }, []);

  return (
    <main className="min-h-screen bg-slate-50 relative pb-20">
      <div className="absolute top-0 w-full h-96 bg-gradient-to-b from-blue-100/50 to-slate-50 pointer-events-none"></div>
      
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 pt-12 relative z-10">
        <div className="flex flex-col md:flex-row md:items-end justify-between mb-12 gap-4">
          <div>
            <div className="inline-flex items-center gap-2 px-3 py-1.5 rounded-full bg-gradient-to-r from-blue-100 to-purple-100 border border-purple-200 text-purple-800 text-xs font-bold tracking-wide uppercase mb-4 shadow-sm">
              <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor" className="w-4 h-4 text-purple-600">
                <path fillRule="evenodd" d="M9 4.5a.75.75 0 01.721.544l.813 2.846a3.75 3.75 0 002.576 2.576l2.846.813a.75.75 0 010 1.442l-2.846.813a3.75 3.75 0 00-2.576 2.576l-.813 2.846a.75.75 0 01-1.442 0l-.813-2.846a3.75 3.75 0 00-2.576-2.576l-2.846-.813a.75.75 0 010-1.442l2.846-.813A3.75 3.75 0 007.466 7.89l.813-2.846A.75.75 0 019 4.5zM18 1.5a.75.75 0 01.728.568l.258 1.036c.236.94.97 1.674 1.91 1.91l1.036.258a.75.75 0 010 1.456l-1.036.258c-.94.236-1.674.97-1.91 1.91l-.258 1.036a.75.75 0 01-1.456 0l-.258-1.036a2.625 2.625 0 00-1.91-1.91l-1.036-.258a.75.75 0 010-1.456l1.036-.258a2.625 2.625 0 001.91-1.91l.258-1.036A.75.75 0 0118 1.5zM16.5 15a.75.75 0 01.712.513l.394 1.183c.15.447.5.799.948.948l1.183.395a.75.75 0 010 1.422l-1.183.395c-.447.15-.799.5-.948.948l-.395 1.183a.75.75 0 01-1.422 0l-.395-1.183a1.5 1.5 0 00-.948-.948l-1.183-.395a.75.75 0 010-1.422l1.183-.395c.447-.15.799-.5.948-.948l.395-1.183A.75.75 0 0116.5 15z" clipRule="evenodd" />
              </svg>
              Generated by ProjectSphere
            </div>
            <h1 className="text-4xl font-extrabold text-gray-900 tracking-tight">Recommended Projects</h1>
            <p className="text-gray-600 mt-2 text-lg max-w-2xl">
              Based on your skills and goals, our AI has analyzed millions of data points to curate these tailored final-year project ideas.
            </p>
          </div>
          <Link href="/onboarding" className="text-blue-600 hover:text-blue-800 font-medium bg-white px-5 py-2.5 rounded-full shadow-sm border hover:shadow transition-all whitespace-nowrap">
            Refine Criteria
          </Link>
        </div>

        {isLoading ? (
          <div className="flex flex-col items-center justify-center py-20">
            <div className="w-16 h-16 border-4 border-blue-200 border-t-blue-600 rounded-full animate-spin mb-6"></div>
            <h2 className="text-2xl font-bold text-gray-800 animate-pulse">AI is engineering your ideas...</h2>
            <p className="text-gray-500 mt-2">Connecting to Gemini Engine</p>
          </div>
        ) : error ? (
          <div className="flex flex-col items-center justify-center py-20">
            <div className="text-5xl mb-4">⚠️</div>
            <h2 className="text-2xl font-bold text-red-600 mb-2">Oops! Something went wrong.</h2>
            <p className="text-gray-600 text-center max-w-md">{error}</p>
            <Link href="/onboarding" className="mt-6 px-6 py-2 bg-gray-900 text-white rounded-lg font-bold hover:bg-gray-800">
              Try Again
            </Link>
          </div>
        ) : (
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-8">
            {projects.map((project) => (
              <div key={project.id} className="bg-white rounded-2xl p-6 shadow-sm border border-gray-100 hover:shadow-2xl hover:-translate-y-2 transition-all duration-300 flex flex-col group relative overflow-hidden">
                <div className={`absolute top-0 left-0 w-full h-1.5 bg-gradient-to-r ${project.color || 'from-blue-400 to-purple-600'}`}></div>
                
                <div className="flex justify-between items-start mb-4">
                  <span className={`bg-gradient-to-r ${project.color || 'from-blue-400 to-purple-600'} text-white px-3 py-1 rounded-md text-xs font-bold shadow-sm`}>
                    {project.match || '90%'} Match
                  </span>
                  <span className="text-sm font-medium text-gray-500 bg-gray-50 px-2 py-1 rounded-md">{project.time || '3 Months'}</span>
                </div>
                
                <h2 className="text-xl font-bold text-gray-900 mb-3 group-hover:text-blue-600 transition-colors">
                  {project.title}
                </h2>
                <p className="text-gray-600 text-sm mb-6 flex-grow leading-relaxed">
                  {project.desc}
                </p>
                
                <div className="flex flex-wrap gap-2 mb-6">
                  {project.tags?.map((tag: string) => (
                    <span key={tag} className="bg-slate-100 text-slate-700 text-xs px-2.5 py-1 rounded-md font-medium border border-slate-200">
                      {tag}
                    </span>
                  ))}
                </div>
                
                <div className="flex justify-between items-center pt-4 border-t border-gray-100">
                  <span className="text-sm font-medium text-gray-500 flex items-center gap-1">
                    <svg xmlns="http://www.w3.org/2000/svg" className="h-4 w-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                      <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M9 19v-6a2 2 0 00-2-2H5a2 2 0 00-2 2v6a2 2 0 002 2h2a2 2 0 002-2zm0 0V9a2 2 0 012-2h2a2 2 0 012 2v10m-6 0a2 2 0 002 2h2a2 2 0 002-2m0 0V5a2 2 0 012-2h2a2 2 0 012 2v14a2 2 0 01-2 2h-2a2 2 0 01-2-2z" />
                    </svg>
                    {project.difficulty || 'Advanced'}
                  </span>
                  <Link href={`/projects/${project.id}`} className="text-blue-600 hover:text-blue-800 font-semibold text-sm flex items-center gap-1 group-hover:translate-x-1 transition-transform">
                    View Details <span aria-hidden="true">&rarr;</span>
                  </Link>
                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    </main>
  );
}
